"""Prepare Mac IDE paths and register one SDK without changing other project defaults."""

from __future__ import annotations

import argparse
import json
import logging
import os
import platform
import subprocess
import tempfile
import uuid
from pathlib import Path
from xml.etree import ElementTree as ET

OWNER = "Generated by FPVS Studio Mac setup."


def _xml_root(path: Path) -> ET.Element:
    parser = ET.XMLParser(target=ET.TreeBuilder(insert_comments=True))
    return ET.parse(path, parser=parser).getroot()


def _save_xml(path: Path, document: ET.Element, backup_dir: Path) -> None:
    before = path.read_bytes() if path.exists() else None
    ET.indent(document, space="  ")
    content = ET.tostring(document, encoding="utf-8") + b"\n"
    if before == content:
        return
    if before is not None:
        backup_dir.mkdir(parents=True, exist_ok=True)
        backup = backup_dir / f"{path.name}.{uuid.uuid4().hex}.bak"
        backup.write_bytes(before)
        backup.chmod(0o600)
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(dir=path.parent, prefix=".fpvs-sdk-")
    try:
        with os.fdopen(descriptor, "wb") as output:
            output.write(content)
        current = path.read_bytes() if path.exists() else None
        if current != before:
            raise ValueError("IDE settings changed during setup. Quit PyCharm and retry.")
        os.replace(temporary, path)
    finally:
        Path(temporary).unlink(missing_ok=True)


def register_pycharm(
    repo_root: Path, python: Path, app: str, *, config_home: Path | None = None,
) -> Path:
    """Add/reuse an SDK and bind this checkout only; leave unrelated SDKs/components intact."""

    candidates = (Path(app).expanduser(), Path("/Applications") / app,
                  Path.home() / "Applications" / app)
    selected = next((path for path in candidates
                     if (path / "Contents/Resources/product-info.json").is_file()), None)
    if selected is None:
        raise ValueError("Install PyCharm, or set FPVS_PYCHARM_APP to its .app path.")
    info = json.loads((selected / "Contents/Resources/product-info.json").read_text())
    profile = info["dataDirectoryName"]
    if not profile.startswith("PyCharm") or Path(profile).name != profile:
        raise ValueError("Unrecognized PyCharm settings profile; no SDK settings were changed.")
    config_home = config_home or Path.home() / "Library/Application Support/JetBrains"
    repo_root = repo_root.absolute()
    table_path = config_home / profile / "options/jdk.table.xml"
    if table_path.is_symlink():
        raise ValueError("Preserving symlinked SDK settings; configure this SDK in the IDE.")
    backups = repo_root / ".fpvs-macos/pycharm-backups"
    if not backups.resolve().is_relative_to(repo_root.resolve()):
        raise ValueError("IDE backups must stay inside this checkout.")
    misc = repo_root / ".idea/misc.xml"
    module = repo_root / ".idea" / f"{repo_root.name}.iml"
    if misc.is_symlink() or module.is_symlink():
        raise ValueError("Preserving symlinked project settings; configure them in the IDE.")
    document = _xml_root(table_path) if table_path.exists() else ET.Element("application")
    if document.tag != "application":
        raise ValueError("Unrecognized SDK settings format; preserving the existing file.")
    table = document.find("component[@name='ProjectJdkTable']")
    if table is None:
        table = ET.SubElement(document, "component", name="ProjectJdkTable")
    python = python.absolute()
    sdk_name = None
    names = set()
    for sdk in table.findall("jdk"):
        name = sdk.find("name")
        home = sdk.find("homePath")
        kind = sdk.find("type")
        if name is not None:
            names.add(name.get("value"))
        if (name is not None and home is not None and kind is not None
                and kind.get("value") == "Python SDK"):
            home_path = Path(home.get("value", "").replace("$USER_HOME$", str(Path.home())))
            if home_path.absolute() == python:
                sdk_name = name.get("value")
    if sdk_name is None:
        base_name = f"Python 3.10 (FPVS Studio Mac: {repo_root.name})"
        sdk_name = base_name
        suffix = 2
        while sdk_name in names:
            sdk_name = f"{base_name} [{suffix}]"
            suffix += 1
        sdk = ET.SubElement(table, "jdk", version="2")
        for tag, value in (("name", sdk_name), ("type", "Python SDK"),
                           ("version", f"Python {platform.python_version()}"),
                           ("homePath", str(python))):
            ET.SubElement(sdk, tag, value=value)
        roots = ET.SubElement(sdk, "roots")
        for tag in ("classPath", "sourcePath"):
            ET.SubElement(ET.SubElement(roots, tag), "root", type="composite")
        ET.SubElement(sdk, "additional", ASSOCIATED_PROJECT_PATH=str(repo_root),
                      SDK_UUID=str(uuid.uuid4()))
        _save_xml(table_path, document, backups)
    project = _xml_root(misc) if misc.exists() else ET.Element("project", version="4")
    manager = project.find("component[@name='ProjectRootManager']")
    if manager is None:
        manager = ET.SubElement(project, "component", name="ProjectRootManager", version="2")
    if (manager.get("project-jdk-name") != sdk_name
            or manager.get("project-jdk-type") != "Python SDK"):
        manager.set("project-jdk-name", sdk_name)
        manager.set("project-jdk-type", "Python SDK")
        _save_xml(misc, project, backups)
    if module.exists():
        tree = _xml_root(module)
        sdk_entry = tree.find(".//orderEntry[@type='jdk'][@jdkType='Python SDK']")
        if sdk_entry is not None and sdk_entry.get("jdkName") != sdk_name:
            sdk_entry.set("jdkName", sdk_name)
            _save_xml(module, tree, backups)
    return selected.absolute()


def launch_pycharm(repo_root: Path, python: Path, app: str) -> None:
    if subprocess.run(["pgrep", "-x", "pycharm"], capture_output=True, check=False).returncode == 0:
        raise ValueError("Quit PyCharm before registering this project's interpreter.")
    configure_pycharm(repo_root, python)
    selected = register_pycharm(repo_root, python, app)
    environment = os.environ.copy()
    environment.pop("PYCHARM_PYTHON_PATH", None)
    subprocess.run(["open", "-na", str(selected), "--args", str(repo_root)],
                   env=environment, check=True)


def configure_pycharm(repo_root: Path, python: Path) -> Path:
    """Keep the venv executable path intact and preserve unrelated/custom IDE files."""

    repo_root = repo_root.absolute()
    python = python.absolute()  # Resolving a venv symlink would select its base Python.
    if not (repo_root / "src/fpvs_studio/app/main.py").is_file() or not python.is_file():
        raise ValueError("Studio source and its installed virtual environment must exist first.")
    target = repo_root / ".idea/runConfigurations/FPVS_Studio_Mac.xml"
    if target.is_symlink() or not target.parent.resolve().is_relative_to(repo_root.resolve()):
        raise ValueError("PyCharm run configuration must stay inside this checkout.")
    if target.exists() and OWNER not in target.read_text(encoding="utf-8"):
        raise ValueError(
            f"Preserving an existing custom configuration: {target}. "
            "Rename that file before rerunning Setup Mac.command."
        )
    document = ET.Element("component", name="ProjectRunConfigurationManager")
    document.append(ET.Comment(f" {OWNER} "))
    configuration = ET.SubElement(
        document, "configuration", default="false", name="FPVS Studio (Mac)",
        type="PythonConfigurationType", factoryName="Python",
    )
    ET.SubElement(configuration, "module", name=repo_root.name)
    for name, value in {
        "SDK_HOME": str(python),
        "IS_MODULE_SDK": "false",
        "WORKING_DIRECTORY": "$PROJECT_DIR$",
        "SCRIPT_NAME": "$PROJECT_DIR$/src/fpvs_studio/app/main.py",
        "MODULE_MODE": "false",
        "ADD_CONTENT_ROOTS": "true",
        "ADD_SOURCE_ROOTS": "true",
        "PARAMETERS": "",
    }.items():
        ET.SubElement(configuration, "option", name=name, value=value)
    ET.SubElement(configuration, "method", v="2")
    ET.indent(document, space="  ")
    content = ET.tostring(document, encoding="unicode") + "\n"
    if not target.exists() or target.read_text(encoding="utf-8") != content:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
    return target


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("repo_root", type=Path)
    parser.add_argument("python", type=Path)
    parser.add_argument("--launch", metavar="PYCHARM_APP")
    arguments = parser.parse_args()
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    if arguments.launch:
        launch_pycharm(arguments.repo_root, arguments.python, arguments.launch)
    else:
        target = configure_pycharm(arguments.repo_root, arguments.python)
        logging.getLogger(__name__).info("PyCharm run configuration: %s", target)


if __name__ == "__main__":
    main()
