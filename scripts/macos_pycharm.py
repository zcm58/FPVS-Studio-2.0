from xml.etree import ElementTree as ET

OWNER = "Generated by FPVS Studio Mac setup."
_UNSPECIFIED = object()
_LOGGER = logging.getLogger("fpvs_studio.pycharm")


def _xml_root(path: Path) -> ET.Element:
    parser = ET.XMLParser(target=ET.TreeBuilder(insert_comments=True))
    return ET.parse(path, parser=parser).getroot()


def _save_xml(
    path: Path, document: ET.Element, backup_dir: Path,
    *, expected_before: bytes | None | object = _UNSPECIFIED,
) -> None:
    before = path.read_bytes() if path.exists() else None
    if expected_before is not _UNSPECIFIED and before != expected_before:
        raise ValueError("IDE settings changed during repair. Retry after the IDE is closed.")
    ET.indent(document, space="  ")
    content = ET.tostring(document, encoding="utf-8") + b"\n"
    if before == content:
        return
    if before is not None:
        backup_dir.mkdir(parents=True, exist_ok=True)
        backup = backup_dir / f"{path.name}.{uuid.uuid4().hex}.bak"
        backup.write_bytes(before)
        backup.chmod(0o600)
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(dir=path.parent, prefix=".fpvs-sdk-")
    try:
        with os.fdopen(descriptor, "wb") as output:
            output.write(content)
        current = path.read_bytes() if path.exists() else None
        if current != before:
            raise ValueError("IDE settings changed during setup. Quit PyCharm and retry.")
        os.replace(temporary, path)
    finally:
        Path(temporary).unlink(missing_ok=True)


def register_pycharm(
    repo_root: Path, python: Path, app: str, *, config_home: Path | None = None,
    config_dir: Path | None = None, python_version: str | None = None,
) -> Path:
    """Add/reuse an SDK and bind this checkout only; leave unrelated SDKs/components intact."""

    candidates = (Path(app).expanduser(), Path("/Applications") / app,
                  Path.home() / "Applications" / app)
    selected = next((path for path in candidates
                     if (path / "Contents/Resources/product-info.json").is_file()), None)
    if selected is None:
        raise ValueError("Install PyCharm, or set FPVS_PYCHARM_APP to its .app path.")
    info = json.loads((selected / "Contents/Resources/product-info.json").read_text())
    profile = info["dataDirectoryName"]
    if not profile.startswith("PyCharm") or Path(profile).name != profile:
        raise ValueError("Unrecognized PyCharm settings profile; no SDK settings were changed.")
    config_home = config_home or Path.home() / "Library/Application Support/JetBrains"
    repo_root = repo_root.absolute()
    table_path = (config_dir or config_home / profile) / "options/jdk.table.xml"
    if table_path.is_symlink():
        raise ValueError("Preserving symlinked SDK settings; configure this SDK in the IDE.")
    backups = repo_root / ".fpvs-macos/pycharm-backups"
    if not backups.resolve().is_relative_to(repo_root.resolve()):
        raise ValueError("IDE backups must stay inside this checkout.")
    misc = repo_root / ".idea/misc.xml"
    module = repo_root / ".idea" / f"{repo_root.name}.iml"
    if (misc.is_symlink() or module.is_symlink()
            or not misc.parent.resolve().is_relative_to(repo_root.resolve())):
        raise ValueError("Preserving symlinked project settings; configure them in the IDE.")
    table_before = table_path.read_bytes() if table_path.exists() else None
    document = _xml_root(table_path) if table_before is not None else ET.Element("application")
    if document.tag != "application":
        raise ValueError("Unrecognized SDK settings format; preserving the existing file.")
    table = document.find("component[@name='ProjectJdkTable']")
    if table is None:
        table = ET.SubElement(document, "component", name="ProjectJdkTable")
    python = python.absolute()
    sdk_name = None
    table_changed = False
    names = set()
    for sdk in table.findall("jdk"):
        name = sdk.find("name")
        home = sdk.find("homePath")
        kind = sdk.find("type")
        if name is not None:
            names.add(name.get("value"))
        if (name is not None and home is not None and kind is not None
                and kind.get("value") == "Python SDK"):
            home_path = Path(home.get("value", "").replace("$USER_HOME$", str(Path.home())))
            if home_path.absolute() == python:
                sdk_name = name.get("value")
                if python_version is not None:
                    version = sdk.find("version")
                    if version is None:
                        version = ET.SubElement(sdk, "version")
                    if version.get("value") != f"Python {python_version}":
                        version.set("value", f"Python {python_version}")
                        table_changed = True
    if sdk_name is None:
        base_name = f"Python 3.10 (FPVS Studio Mac: {repo_root.name})"
        sdk_name = base_name
        suffix = 2
        while sdk_name in names:
            sdk_name = f"{base_name} [{suffix}]"
            suffix += 1
        sdk = ET.SubElement(table, "jdk", version="2")
        for tag, value in (("name", sdk_name), ("type", "Python SDK"),
                           ("version", f"Python {python_version or platform.python_version()}"),
                           ("homePath", str(python))):
            ET.SubElement(sdk, tag, value=value)
        roots = ET.SubElement(sdk, "roots")
        for tag in ("classPath", "sourcePath"):
            ET.SubElement(ET.SubElement(roots, tag), "root", type="composite")
        ET.SubElement(sdk, "additional", ASSOCIATED_PROJECT_PATH=str(repo_root),
                      SDK_UUID=str(uuid.uuid4()))
        table_changed = True
    if table_changed:
        _save_xml(table_path, document, backups, expected_before=table_before)
    project_before = misc.read_bytes() if misc.exists() else None
    project = _xml_root(misc) if project_before is not None else ET.Element("project", version="4")
    manager = project.find("component[@name='ProjectRootManager']")
    if manager is None:
        manager = ET.SubElement(project, "component", name="ProjectRootManager", version="2")
    if (manager.get("project-jdk-name") != sdk_name
            or manager.get("project-jdk-type") != "Python SDK"):
        manager.set("project-jdk-name", sdk_name)
        manager.set("project-jdk-type", "Python SDK")
        _save_xml(misc, project, backups, expected_before=project_before)
    if module.exists():
        module_before = module.read_bytes()
        tree = _xml_root(module)
        sdk_entry = tree.find(".//orderEntry[@type='jdk'][@jdkType='Python SDK']")
        if sdk_entry is not None and sdk_entry.get("jdkName") != sdk_name:
            sdk_entry.set("jdkName", sdk_name)
            _save_xml(module, tree, backups, expected_before=module_before)
    return selected.absolute()


def launch_pycharm(repo_root: Path, python: Path, app: str) -> None:
    if subprocess.run(["pgrep", "-x", "pycharm"], capture_output=True, check=False).returncode == 0:
        raise ValueError("Quit PyCharm before registering this project's interpreter.")
    configure_pycharm(repo_root, python)
    selected = register_pycharm(repo_root, python, app)
    environment = os.environ.copy()
    environment.pop("PYCHARM_PYTHON_PATH", None)
    subprocess.run(["open", "-na", str(selected), "--args", str(repo_root)],
                   env=environment, check=True)


def configure_pycharm(repo_root: Path, python: Path) -> Path:
    """Keep the venv executable path intact and preserve unrelated/custom IDE files."""

    repo_root = repo_root.absolute()
    python = python.absolute()  # Resolving a venv symlink would select its base Python.
    if not (repo_root / "src/fpvs_studio/app/main.py").is_file() or not python.is_file():
        raise ValueError("Studio source and its installed virtual environment must exist first.")
    target = repo_root / ".idea/runConfigurations/FPVS_Studio_Mac.xml"
    if target.is_symlink() or not target.parent.resolve().is_relative_to(repo_root.resolve()):
        raise ValueError("PyCharm run configuration must stay inside this checkout.")
    if target.exists() and OWNER not in target.read_text(encoding="utf-8"):
        raise ValueError(
            f"Preserving an existing custom configuration: {target}. "
            "Rename that file before rerunning Setup Mac.command."
        )
    document = ET.Element("component", name="ProjectRunConfigurationManager")
    document.append(ET.Comment(f" {OWNER} "))
    configuration = ET.SubElement(
        document, "configuration", default="false", name="FPVS Studio (Mac)",
        type="PythonConfigurationType", factoryName="Python",
    )
    ET.SubElement(configuration, "module", name=repo_root.name)
    for name, value in {
        "SDK_HOME": str(python),
        "IS_MODULE_SDK": "false",
        "WORKING_DIRECTORY": "$PROJECT_DIR$",
        "SCRIPT_NAME": "$PROJECT_DIR$/src/fpvs_studio/app/main.py",
        "MODULE_MODE": "false",
        "ADD_CONTENT_ROOTS": "true",
        "ADD_SOURCE_ROOTS": "true",
        "PARAMETERS": "",
    }.items():
        ET.SubElement(configuration, "option", name=name, value=value)
    ET.SubElement(configuration, "method", v="2")
    ET.indent(document, space="  ")
    content = ET.tostring(document, encoding="unicode") + "\n"
    if not target.exists() or target.read_text(encoding="utf-8") != content:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
    return target


class RepairIDE:
    def __init__(self, app: Path, config_dir: Path, pids: tuple[int, ...] = ()) -> None:
        self.app = app
        self.config_dir = config_dir
        self.pids = pids


def _app_details(app: Path) -> tuple[Path, str]:
    app = app.expanduser().absolute()
    info_path = app / "Contents/Resources/product-info.json"
    info = json.loads(info_path.read_text(encoding="utf-8"))
    profile = info.get("dataDirectoryName", "")
    if (not isinstance(profile, str) or not profile.startswith("PyCharm")
            or Path(profile).name != profile):
        raise ValueError("The selected application is not a recognized PyCharm installation.")
    return app, profile


def _process_value(pid: int, field: str) -> str:
    result = subprocess.run(
        ["/bin/ps", "-p", str(pid), "-o", f"{field}="],
        capture_output=True, text=True, check=False, timeout=10,
    )
    return result.stdout.strip() if result.returncode == 0 else ""


def _app_for_pid(pid: int) -> Path | None:
    executable = Path(_process_value(pid, "comm"))
    for parent in executable.parents:
        if parent.suffix == ".app" and (parent / "Contents/Resources/product-info.json").is_file():
            app, _profile = _app_details(parent)
            return app
    return None


def _running_pycharm_pids() -> tuple[int, ...]:
    result = subprocess.run(
        ["/usr/bin/pgrep", "-x", "pycharm"],
        capture_output=True, text=True, check=False, timeout=10,
    )
    if result.returncode == 1:
        return ()
    if result.returncode != 0:
        raise ValueError("Could not determine whether PyCharm is running; no IDE settings changed.")
    return tuple(int(value) for value in result.stdout.split())


def _active_config_dir(app: Path, pid: int) -> Path:
    candidates = (
        app / "Contents/jbr/Contents/Home/bin/jcmd",
        app / "Contents/jbr/bin/jcmd",
        app / "Contents/jdk/Contents/Home/bin/jcmd",
    )
    jcmd = next((candidate for candidate in candidates if candidate.is_file()), None)
    if jcmd is None:
        raise ValueError(
            "Cannot identify the running PyCharm settings: its Java diagnostic tool is missing."
        )
    result = subprocess.run(
        [str(jcmd), str(pid), "VM.system_properties"],
        capture_output=True, text=True, check=False, timeout=20,
    )
    if result.returncode == 0:
        for line in result.stdout.splitlines():
            name, separator, value = line.partition("=")
            if separator and name.strip() == "idea.config.path" and value.strip():
                def unescape(match: re.Match[str]) -> str:
                    escaped = match.group(1)
                    if escaped.startswith("u") and len(escaped) == 5:
                        return chr(int(escaped[1:], 16))
                    return {"t": "\t", "n": "\n", "r": "\r", "f": "\f"}.get(escaped, escaped)

                decoded = re.sub(r"\\(u[0-9a-fA-F]{4}|.)", unescape, value.strip())
                path = Path(decoded).expanduser()
                if path.is_absolute():
                    return path.absolute()
    raise ValueError(
        "Could not read the running PyCharm settings location; no IDE settings changed."
    )


def _discover_repair_ide() -> RepairIDE:
    active: list[tuple[int, Path, Path]] = []
    for pid in _running_pycharm_pids():
        app = _app_for_pid(pid)
        if app is None:
            raise ValueError(
                "Could not identify a running PyCharm application; no IDE settings changed."
            )
        active.append((pid, app, _active_config_dir(app, pid)))
    ancestors: set[int] = set()
    pid = os.getppid()
    for _ in range(64):
        if pid <= 1 or pid in ancestors:
            break
        ancestors.add(pid)
        parent = _process_value(pid, "ppid")
        if not parent:
            break
        pid = int(parent)
    owner = next((item for item in active if item[0] in ancestors), None)
    explicit = os.environ.get("FPVS_PYCHARM_APP")
    if owner is None and active:
        matches = [item for item in active if not explicit or item[1] == Path(explicit).absolute()]
        if len(matches) != 1:
            raise ValueError(
                "Multiple PyCharm instances are open. Run this helper from the Studio IDE."
            )
        owner = matches[0]
    if owner is not None:
        _pid, app, config = owner
        if any(item[1] != app and item[2].resolve() == config.resolve() for item in active):
            raise ValueError(
                "Different PyCharm installations share this profile. Close the other IDE."
            )
        pids = tuple(item[0] for item in active if item[2].resolve() == config.resolve())
        return RepairIDE(app, config, pids)
    candidates = ((Path(explicit).expanduser(),) if explicit else (
        Path("/Applications/PyCharm.app"), Path.home() / "Applications/PyCharm.app",
    ))
    app = next((candidate for candidate in candidates
                if (candidate / "Contents/Resources/product-info.json").is_file()), None)
    if app is None:
        raise ValueError(
            "Could not locate PyCharm. Run the helper from PyCharm or set FPVS_PYCHARM_APP."
        )
    app, profile = _app_details(app)
    config = Path.home() / "Library/Application Support/JetBrains" / profile
    # A custom profile must be learned from the running IDE, rather than guessed.
    properties = [app / "Contents/bin/idea.properties", config / "idea.properties"]
    if os.environ.get("PYCHARM_PROPERTIES"):
        properties.append(Path(os.environ["PYCHARM_PROPERTIES"]).expanduser())
    for path in properties:
        if path.is_file() and any(
            line.strip().startswith("idea.config.path")
            for line in path.read_text(encoding="utf-8").splitlines()
        ):
            raise ValueError(
                "Open PyCharm and run the helper there to identify its custom settings."
            )
    return RepairIDE(app, config)


def _repair_paths(repo_root: Path, ide: RepairIDE) -> Path:
    backups = repo_root / ".fpvs-macos/pycharm-backups"
    for path in (
        repo_root / ".idea", repo_root / ".idea/runConfigurations",
        repo_root / ".fpvs-macos", backups,
    ):
        if path.is_symlink() or not path.resolve().is_relative_to(repo_root.resolve()):
            raise ValueError("IDE settings and backups must stay inside the Studio checkout.")
    for path in (ide.config_dir, ide.config_dir / "options"):
        if path.is_symlink():
            raise ValueError("Preserving symlinked PyCharm settings; no settings were changed.")
    return backups


def _read_repair_xml(path: Path, tag: str) -> tuple[ET.Element, bytes | None]:
    if path.is_symlink():
        raise ValueError(f"Preserving symlinked IDE file: {path}")
    before = path.read_bytes() if path.exists() else None
    try:
        document = (_xml_root(path) if before is not None else ET.Element(tag))
    except ET.ParseError as exc:
        raise ValueError(f"Preserving invalid IDE XML: {path}") from exc
    if document.tag != tag:
        raise ValueError(f"Preserving unrecognized IDE settings: {path}")
    return document, before


def _sdk_name(table: ET.Element, python: Path) -> str | None:
    for entry in table.findall("component[@name='ProjectJdkTable']/jdk"):
        home, kind, name = entry.find("homePath"), entry.find("type"), entry.find("name")
        if home is not None and kind is not None and name is not None:
            value = home.get("value", "").replace("$USER_HOME$", str(Path.home()))
            if kind.get("value") == "Python SDK" and Path(value).absolute() == python.absolute():
                return name.get("value")
    return None


def _options(configuration: ET.Element) -> dict[str, str]:
    return {item.get("name", ""): item.get("value", "") for item in configuration.findall("option")}


def _studio_configuration(configuration: ET.Element, repo_root: Path) -> bool:
    if configuration.get("type") != "PythonConfigurationType":
        return False
    options = _options(configuration)
    script = options.get("SCRIPT_NAME", "")
    if options.get("MODULE_MODE", "false").lower() == "true":
        return script in ("fpvs_studio.app", "fpvs_studio.app.main")

    def expanded(value: str) -> Path:
        return Path(value.replace("$PROJECT_DIR$", str(repo_root)).replace(
            "$MODULE_WORKING_DIR$", str(repo_root),
        ).replace("$USER_HOME$", str(Path.home()))).expanduser()

    path = expanded(script)
    if not path.is_absolute():
        working = expanded(options.get("WORKING_DIRECTORY", str(repo_root)))
        path = (working if working.is_absolute() else repo_root / working) / path
    return path.resolve() in (
        (repo_root / "src/fpvs_studio/app/main.py").resolve(),
        (repo_root / "scripts/macos_repair_environment.py").resolve(),
    )


def _project_documents(repo_root: Path) -> list[tuple[Path, ET.Element, bytes | None]]:
    workspace = repo_root / ".idea/workspace.xml"
    result = [(workspace, *_read_repair_xml(workspace, "project"))]
    directory = repo_root / ".idea/runConfigurations"
    for path in sorted(directory.glob("*.xml")):
        result.append((path, *_read_repair_xml(path, "component")))
    return result


def _interpreter_matches(configuration: ET.Element, python: Path, sdk_name: str) -> bool:
    values = _options(configuration)
    return (values.get("SDK_HOME") == str(python.absolute())
            and values.get("IS_MODULE_SDK", "true").lower() == "false"
            and values.get("SDK_NAME", sdk_name) == sdk_name)


def _repair_settings_ready(repo_root: Path, python: Path, ide: RepairIDE) -> bool:
    _repair_paths(repo_root, ide)
    table, _ = _read_repair_xml(ide.config_dir / "options/jdk.table.xml", "application")
    sdk = _sdk_name(table, python)
    sdk_version_matches = False
    if sdk:
        expected_version = f"Python {_target_python_version(python)}"
        for entry in table.findall("component[@name='ProjectJdkTable']/jdk"):
            name, version = entry.find("name"), entry.find("version")
            if name is not None and name.get("value") == sdk and version is not None:
                sdk_version_matches = version.get("value") == expected_version
    misc, _ = _read_repair_xml(repo_root / ".idea/misc.xml", "project")
    manager = misc.find("component[@name='ProjectRootManager']")
    ready = bool(sdk and sdk_version_matches and manager is not None
                 and manager.get("project-jdk-name") == sdk
                 and manager.get("project-jdk-type") == "Python SDK")
    module = repo_root / ".idea" / f"{repo_root.name}.iml"
    if module.exists():
        tree, _ = _read_repair_xml(module, "module")
        for entry in tree.findall(".//orderEntry[@type='jdk'][@jdkType='Python SDK']"):
            ready = ready and entry.get("jdkName") == sdk
    generated = repo_root / ".idea/runConfigurations/FPVS_Studio_Mac.xml"
    generated_found = False
    for path, document, _before in _project_documents(repo_root):
        configurations = list(document.iter("configuration"))
        if path == generated:
            if len(configurations) != 1 or not _studio_configuration(configurations[0], repo_root):
                raise ValueError(
                    "Preserving a custom FPVS_Studio_Mac.xml that does not launch Studio."
                )
            generated_found = True
        for configuration in configurations:
            if _studio_configuration(configuration, repo_root):
                ready = ready and _interpreter_matches(configuration, python, sdk or "")
    return ready and generated_found


def _set_option(configuration: ET.Element, name: str, value: str) -> None:
    option = configuration.find(f"option[@name='{name}']")
    if option is None:
        option = ET.SubElement(configuration, "option", name=name)
    option.set("value", value)


def _target_python_version(python: Path) -> str:
    result = subprocess.run(
        [str(python), "-I", "-c",
         "import platform,sys; sys.stdout.write(platform.python_version())"],
        capture_output=True, text=True, check=True, timeout=20,
    )
    value = result.stdout.strip()
    if not value.startswith("3.10."):
        raise ValueError("The verified Studio environment must use Python 3.10.")
    return value


def _apply_repair_settings(repo_root: Path, python: Path, ide: RepairIDE) -> None:
    backups = _repair_paths(repo_root, ide)
    # Read all targeted XML before the first mutation, so malformed/custom files
    # cannot leave a half-configured profile merely because they were found late.
    _repair_settings_ready(repo_root, python, ide)
    register_pycharm(
        repo_root, python, str(ide.app), config_dir=ide.config_dir,
        python_version=_target_python_version(python),
    )
    generated = repo_root / ".idea/runConfigurations/FPVS_Studio_Mac.xml"
    if not generated.exists():
        configure_pycharm(repo_root, python)
    table, _ = _read_repair_xml(ide.config_dir / "options/jdk.table.xml", "application")
    sdk = _sdk_name(table, python)
    if sdk is None:
        raise ValueError("PyCharm SDK registration did not persist.")
    documents = _project_documents(repo_root)
    selected = "FPVS Studio (Mac)"
    for path, document, before in documents:
        touched = False
        for configuration in document.iter("configuration"):
            if _studio_configuration(configuration, repo_root):
                if not _interpreter_matches(configuration, python, sdk):
                    _set_option(configuration, "SDK_HOME", str(python.absolute()))
                    _set_option(configuration, "SDK_NAME", sdk)
                    _set_option(configuration, "IS_MODULE_SDK", "false")
                    touched = True
                if path == generated:
                    selected = configuration.get("name", selected)
        if touched and path != repo_root / ".idea/workspace.xml":
            _save_xml(path, document, backups, expected_before=before)
    workspace, document, before = documents[0]
    manager = document.find("component[@name='RunManager']")
    if manager is None:
        manager = ET.SubElement(document, "component", name="RunManager")
    manager.set("selected", f"Python.{selected}")
    _save_xml(workspace, document, backups, expected_before=before)
    if not _repair_settings_ready(repo_root, python, ide):
        raise ValueError("PyCharm interpreter verification failed after saving.")


def _pid_alive(pid: int) -> bool:
    try:
        os.kill(pid, 0)
    except ProcessLookupError:
        return False
    return True


def _normal_quit(pid: int, app: Path) -> None:
    applications = import_module("AppKit").NSRunningApplication
    application = applications.runningApplicationWithProcessIdentifier_(pid)
    if application is None:
        return
    if Path(str(application.bundleURL().path())).absolute() != app.absolute():
        raise ValueError("The PyCharm process changed; no application was closed.")
    if not application.terminate():
        raise ValueError(
            "PyCharm did not accept the normal quit request; no settings were changed."
        )


def _show_repair_result(message: str) -> None:
    script = (
        'on run argv\n'
        'display dialog (item 1 of argv) with title "FPVS Studio environment" '
        'buttons {"OK"} default button "OK" giving up after 60\n'
        'end run'
    )
    subprocess.run(["/usr/bin/osascript", "-e", script, message], check=False, timeout=70)


def _reopen_pycharm(repo_root: Path, app: Path) -> None:
    environment = os.environ.copy()
    environment.pop("PYCHARM_PYTHON_PATH", None)
    subprocess.run(
        ["/usr/bin/open", "-a", str(app), str(repo_root)],
        env=environment, check=True, timeout=30,
    )


def _profile_is_closed(ide: RepairIDE) -> bool:
    for pid in _running_pycharm_pids():
        app = _app_for_pid(pid)
        if app is None:
            raise ValueError("Could not identify a running PyCharm process; no settings changed.")
        if _active_config_dir(app, pid).resolve() == ide.config_dir.resolve():
            return False
    return True


def _job_lock(repo_root: Path, ide: RepairIDE) -> Path:
    profile_key = hashlib.sha256(str(ide.config_dir.resolve()).encode("utf-8")).hexdigest()[:20]
    return repo_root / ".fpvs-macos/pycharm-repair" / f"active-{profile_key}.json"


def _release_job_lock(repo_root: Path, ide: RepairIDE, token: str) -> None:
    path = _job_lock(repo_root, ide)
    if path.is_symlink():
        return
    try:
        before = path.read_bytes()
        if json.loads(before).get("token") == token and path.read_bytes() == before:
            path.unlink()
    except FileNotFoundError:
        pass


def _reserve_job(repo_root: Path, ide: RepairIDE, parent_pid: int) -> tuple[Path, bool]:
    directory = repo_root / ".fpvs-macos/pycharm-repair"
    if directory.is_symlink() or not directory.resolve().is_relative_to(repo_root.resolve()):
        raise ValueError("PyCharm repair files must stay inside the Studio checkout.")
    directory.mkdir(parents=True, exist_ok=True)
    lock = _job_lock(repo_root, ide)
    for _attempt in range(5):
        if lock.is_symlink():
            raise ValueError("Preserving a symlinked PyCharm repair lock.")
        try:
            before = lock.read_bytes()
        except FileNotFoundError:
            before = None
        if before is not None:
            try:
                current = json.loads(before)
                previous = directory / current["job"]
                if (previous.parent != directory or previous.is_symlink()
                        or not re.fullmatch(r"[0-9a-f]{32}\.json", previous.name)):
                    raise ValueError("Invalid pending PyCharm repair; preserving its files.")
                result = previous.with_suffix(".result.json")
                expires = float(current["expires"])
                if expires > time.time() + 301:
                    raise ValueError("Invalid pending PyCharm repair lease; preserving its files.")
                claim = previous.with_suffix(".claim")
                if (not result.exists() and claim.is_file() and not claim.is_symlink()
                        and _pid_alive(int(claim.read_text()))):
                    return previous, False
                if expires > time.time() and not result.exists():
                    return previous, False
                if lock.read_bytes() == before:
                    lock.unlink()
            except (json.JSONDecodeError, FileNotFoundError):
                time.sleep(0.1)
            continue
        token = uuid.uuid4().hex
        job_path = directory / f"{token}.json"
        expires = time.time() + 300
        payload = {
            "version": 1, "token": token, "expires": expires,
            "app": str(ide.app), "config_dir": str(ide.config_dir), "pids": ide.pids,
            "parent_pid": parent_pid,
        }
        try:
            descriptor = os.open(lock, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        except FileExistsError:
            continue
        try:
            with os.fdopen(descriptor, "w") as stream:
                json.dump({"token": token, "expires": expires, "job": job_path.name}, stream)
            with os.fdopen(os.open(
                job_path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600,
            ), "w") as stream:
                json.dump(payload, stream)
            return job_path, True
        except BaseException:
            _release_job_lock(repo_root, ide, token)
            raise
    raise ValueError("Another PyCharm repair is starting. Wait for its result before trying again.")


def _finish_repair(repo_root: Path, python: Path, job_path: Path, token: str) -> int:
    message = ""
    result_path: Path | None = None
    ide: RepairIDE | None = None
    try:
        directory = repo_root / ".fpvs-macos/pycharm-repair"
        if (job_path.is_symlink() or job_path.resolve().parent != directory.resolve()
                or directory.is_symlink()
                or (repo_root / ".fpvs-macos").is_symlink()
                or not directory.resolve().is_relative_to(repo_root.resolve())):
            raise ValueError("Invalid PyCharm repair job path.")
        job = json.loads(job_path.read_text(encoding="utf-8"))
        if job["token"] != token or job["version"] != 1:
            raise ValueError("Invalid PyCharm repair job.")
        deadline = float(job["expires"])
        if not time.time() < deadline <= time.time() + 300:
            raise ValueError("The PyCharm repair request expired; run the helper again.")
        ide = RepairIDE(Path(job["app"]), Path(job["config_dir"]), tuple(job["pids"]))
        lock = _job_lock(repo_root, ide)
        if lock.is_symlink() or json.loads(lock.read_text())["token"] != token:
            raise ValueError("This PyCharm repair no longer owns the active request.")
        candidate_result = job_path.with_suffix(".result.json")
        if candidate_result.exists() or candidate_result.is_symlink():
            raise ValueError("This PyCharm repair already has a result; preserving it.")
        # One worker owns each request. Never repeat a quit or configuration write.
        with os.fdopen(os.open(
            job_path.with_suffix(".claim"), os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600,
        ), "w") as claim:
            claim.write(str(os.getpid()))
        result_path = job_path.with_suffix(".result.json")
        parent_deadline = min(deadline, time.time() + 30)
        while _pid_alive(int(job["parent_pid"])):
            if time.time() >= parent_deadline:
                raise ValueError("The original helper is still running. Retry after it finishes.")
            time.sleep(0.2)
        if time.time() >= deadline:
            raise ValueError("The PyCharm repair request expired; run the helper again.")
        for pid in ide.pids:
            _normal_quit(pid, ide.app)
        while any(_pid_alive(pid) for pid in ide.pids):
            if time.time() >= deadline:
                raise ValueError(
                    "PyCharm stayed open or quitting was canceled. No IDE settings changed."
                )
            time.sleep(0.5)
        if not _profile_is_closed(ide):
            raise ValueError(
                "PyCharm reopened before repair could finish; no IDE settings changed."
            )
        if time.time() >= deadline:
            raise ValueError("The PyCharm repair request expired before settings could be saved.")
        _apply_repair_settings(repo_root, python, ide)
        _reopen_pycharm(repo_root, ide.app)
        message = (
            "Studio's environment and engine imports passed. PyCharm now uses the verified "
            "interpreter and has reopened the project. Run FPVS Studio (Mac) and retry Test/Pilot."
        )
        result = 0
    except Exception as exc:
        _LOGGER.exception("PyCharm repair did not complete")
        message = f"PyCharm repair did not complete: {exc}\nLog: {job_path.with_suffix('.log')}"
        result = 1
    if result_path is not None:
        try:
            with os.fdopen(os.open(
                result_path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600,
            ), "w") as stream:
                json.dump({"success": result == 0, "message": message}, stream)
        except OSError as exc:
            _LOGGER.exception("Could not retain the PyCharm repair result")
            message = (
                f"PyCharm repair did not finish recording its result: {exc}\n"
                f"Log: {job_path.with_suffix('.log')}"
            )
            result = 1
        if ide is not None:
            try:
                _release_job_lock(repo_root, ide, token)
            except (OSError, ValueError) as exc:
                _LOGGER.exception("Could not release this PyCharm repair request")
                message = (
                    f"PyCharm repair did not finish releasing its completion status: {exc}\n"
                    f"Log: {job_path.with_suffix('.log')}"
                )
                result = 1
    _LOGGER.info(message)
    try:
        _show_repair_result(message)
    except (OSError, subprocess.SubprocessError):
        _LOGGER.exception("Could not display the repair result; see the repair log")
    return result


def configure_for_repair(
    repo_root: Path, python: Path, *, check_only: bool = False, parent_pid: int | None = None,
    launch_prefix: str | None = None, launch_version: str | None = None,
) -> str:
    """Verify or repair this project's IDE bindings after its environment is healthy."""

    repo_root, python = repo_root.absolute(), python.absolute()
    if not python.is_file() or not (repo_root / "src/fpvs_studio/app/main.py").is_file():
        raise ValueError("Studio source and its verified environment must exist first.")
    ide = _discover_repair_ide()
    live_interpreter_mismatch = bool(ide.pids) and (
        (launch_prefix is not None
         and Path(launch_prefix).resolve() != python.parent.parent.resolve())
        or (launch_version is not None and launch_version != "3.10")
    )
    if _repair_settings_ready(repo_root, python, ide) and not live_interpreter_mismatch:
        return "ready"
    if check_only:
        raise ValueError(
            "PyCharm uses a different interpreter. Run this helper without --check to fix it."
        )
    if not ide.pids:
        if not _profile_is_closed(ide):
            raise ValueError("PyCharm opened during the check. Run the helper from that IDE.")
        _apply_repair_settings(repo_root, python, ide)
        return "ready"
    job_path, created = _reserve_job(repo_root, ide, parent_pid or os.getpid())
    if not created:
        _LOGGER.info(
            "A PyCharm repair is already pending. Repair log: %s", job_path.with_suffix(".log"),
        )
        return "pending"
    token = job_path.stem
    log_path = job_path.with_suffix(".log")
    try:
        with os.fdopen(os.open(
            log_path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600,
        ), "w") as stream:
            subprocess.Popen(
                [str(python), "-I", str(Path(__file__).absolute()), str(repo_root), str(python),
                 "--finish-repair", str(job_path), "--repair-token", token],
                cwd=repo_root, stdin=subprocess.DEVNULL, stdout=stream,
                stderr=subprocess.STDOUT, start_new_session=True,
            )
    except BaseException:
        _release_job_lock(repo_root, ide, token)
        raise
    _LOGGER.info(
        "Environment verified. PyCharm will now quit normally and reopen with the corrected "
        "interpreter. Save/close any prompts to allow this to finish. Repair log: %s", log_path,
    )
    return "pending"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("repo_root", type=Path)
    parser.add_argument("python", type=Path)
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument("--launch", metavar="PYCHARM_APP")
    modes.add_argument(
        "--repair", action="store_true", help="repair this project's IDE interpreter",
    )
    modes.add_argument("--check", action="store_true", help="check this project's IDE interpreter")
    modes.add_argument("--finish-repair", type=Path, help=argparse.SUPPRESS)
    parser.add_argument("--repair-parent-pid", type=int, help=argparse.SUPPRESS)
    parser.add_argument("--repair-launch-prefix", help=argparse.SUPPRESS)
    parser.add_argument("--repair-launch-version", help=argparse.SUPPRESS)
    parser.add_argument("--repair-token", help=argparse.SUPPRESS)
    arguments = parser.parse_args()
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    if arguments.repair or arguments.check:
        try:
            state = configure_for_repair(
                arguments.repo_root, arguments.python, check_only=arguments.check,
                parent_pid=arguments.repair_parent_pid,
                launch_prefix=arguments.repair_launch_prefix,
                launch_version=arguments.repair_launch_version,
            )
        except (ValueError, OSError, subprocess.SubprocessError) as exc:
            _LOGGER.error("PyCharm interpreter setup stopped: %s", exc)
            raise SystemExit(1) from exc
        raise SystemExit(10 if state == "pending" else 0)
    if arguments.finish_repair:
        raise SystemExit(_finish_repair(
            arguments.repo_root, arguments.python, arguments.finish_repair, arguments.repair_token,
        ))
    if arguments.launch:
        launch_pycharm(arguments.repo_root, arguments.python, arguments.launch)
    else:
        target = configure_pycharm(arguments.repo_root, arguments.python)
        logging.getLogger(__name__).info("PyCharm run configuration: %s", target)


if __name__ == "__main__":
    main()
